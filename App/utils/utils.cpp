/**
 * 각도를 인덱스로 하여 테이블로부터 얻은 값을 선형 보간하여 반환한다.
 */
float GetSineFromTableWithLinearInterpolation(float degree,
                                              unsigned phase_offset) {
  if (!std::isfinite(degree)) {
    return std::numeric_limits<float>::quiet_NaN();
  }
  // 각도 값이 0~360.0을 벗어나는 경우 인덱스로 변환하기 어려우므로 mod 처리
  if (degree < 0.0f || degree >= 360.0f) {
    degree = std::fmod(degree, 360.0f);
    if (degree < 0.0f) degree += 360.0f;
  }
  float position = degree * DEGREE_TO_SIN_TABLE_INDEX;
  unsigned int whole = static_cast<unsigned int>(position);
  float fraction = position - static_cast<float>(whole);
  unsigned index = (whole + phase_offset) & (SIN_TABLE_SIZE - 1);
  float first = SIN_TABLE[index];
  return first + fraction * (SIN_TABLE[index + 1] - first);
}

int16_t AbsInt16(int16_t n) { return n > 0 ? n : -n; }

float CosineFromDegrees(float degree) {
  return GetSineFromTableWithLinearInterpolation(degree, SIN_TABLE_SIZE / 4);
}

float SineFromDegrees(float degree) {
  return GetSineFromTableWithLinearInterpolation(degree, 0);
}

Hash_t djb2(const char* string) {
  Hash_t hash = 5381;
  Hash_t c;
  while (c = *string++) {
    hash = (((hash << 5) + hash) + c) % UINT32_MAX;
  }
  return hash % UINT32_MAX;
}

double MapRangeLinear(double x, double x_min, double x_max, double min,
                      double max) {
  if (x_max == x_min) return min;

  return ((x - x_min) / (x_max - x_min)) * (max - min) + min;
}

float RoundToInt16(float f) { return static_cast<std::int16_t>(f + 0.5f); }

