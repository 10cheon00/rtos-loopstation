float GetCutoffFrequency(ParameterModel::UnsignedRangeValue cutoff) {
  const int index = cutoff.clamp(cutoff.current);
  return CUTOFF_TO_FREQUENCY_TABLE[index];
}

float GetRateFrequency(std::int16_t numeric_rate) {
  const int rate =
      numeric_rate < 0 ? 0 : (numeric_rate > 100 ? 100 : numeric_rate);
  return NUMERIC_RATE_TO_FREQUENCY_TABLE[rate];
}

float GetResonanceQ(std::int16_t resonance) {
  const int index = resonance < 0 ? 0 : (resonance > 100 ? 100 : resonance);
  return RESONANCE_TO_Q_TABLE[index];
}

